-- ace-theory.lua --- maps the booklet's markdown vocabulary onto ace-theory-preamble.tex (single column)
--
--   # Part 3 --- Title          -> \partopener{Part 3}{Title}   (new page, dark band, TOC entry)
--   ## 3.2 Title                -> \sectionband{3.2}{Title}     (teal band)
--   ## 3.14 Part 3 recall card  -> the same, on a new page (it must fit that page: build gate 9)
--   ::: {.objectives}           -> the grey "EXAM GUIDE" line under a part band
--   ::: {.key} ... :::          -> a left-bar tinted panel, breakable across pages; title="..." overrides the label
--   two short adjacent panels   -> side by side (unbreakable half-width panels)
--   > quote                     -> a "thesis" panel: yellow bar, no label
--   ::: {.cmds} + a table       -> a command table (dark header)
--   tables                      -> longtable; column widths measured from the content
--   ```code```                  -> grey code panel (ASCII diagrams, log filters)
--   ==text==                    -> yellow highlighter (needs -f markdown+mark)
--   ::: {.wide}                 -> accepted and ignored (a leftover of the two-column edition)
--
-- The input is generated by assemble.py from the published pages in theory/.
-- A table inside a panel is a hard error: a panel is a box, and a box cannot hold a longtable.

local PANELS = {
  key    = { "blue",    "bluebg",    "Remember this" },
  trap   = { "red",     "redbg",     "Exam trap" },
  tip    = { "green",   "greenbg",   "How to spot it" },
  watch  = { "amber",   "amberbg",   "Easy to confuse" },
  note   = { "teal",    "tealbg",    "Worth knowing" },
  new    = { "magenta", "magentabg", "New in the June 2026 guide" },
}

local CODE_CHARS = 150        -- what a code panel holds across the page at \codesize
local TABLE_CHARS = 130       -- characters across a full-width table at \tablesize
local PAIR_MAX = 720          -- a panel this short (characters) may sit beside another
local PAIR_RATIO = 2.3        -- ... if neither is more than this many times the other

-- Parts to set in the tighter rhythm (\acetight), e.g. ACE_TIGHT="PART 3,APPENDIX A". build-theory.sh sets
-- it for parts whose last page would otherwise hold only a few lines.
local TIGHT = {}
for label in (os.getenv("ACE_TIGHT") or ""):gmatch("[^,]+") do TIGHT[label:upper()] = true end

local function latex_escape(s)
  s = s:gsub("\\", "\\textbackslash{}")
  s = s:gsub("([&%%#_{}%$])", "\\%1")
  return s
end

local function raw(s) return pandoc.RawBlock("latex", s) end
local function rawi(s) return pandoc.RawInline("latex", s) end

local function inline_latex(inls)
  return (pandoc.write(pandoc.Pandoc({ pandoc.Plain(inls) }), "latex"):gsub("%s+$", ""))
end

local function blocks_latex(blocks)
  local s = pandoc.write(pandoc.Pandoc(blocks), "latex"):gsub("%s+$", "")
  return (s:gsub("\n\n+", "\\par{}"):gsub("\n", " "))
end

------------------------------------------------------------------------ inline pass
-- Helvetica Neue has no arrows; Latin Modern math does. Code blocks (Menlo) keep theirs.
local GLYPHS = { ["→"] = "\\ensuremath{\\rightarrow}", ["←"] = "\\ensuremath{\\leftarrow}",
                 ["↔"] = "\\ensuremath{\\leftrightarrow}", ["⇒"] = "\\ensuremath{\\Rightarrow}" }
local function Str(el)
  local s = el.text
  local hit = false
  for g in pairs(GLYPHS) do if s:find(g, 1, true) then hit = true end end
  if not hit then return nil end
  local out, buf, i = pandoc.List(), "", 1
  while i <= #s do
    local matched = false
    for g, tex in pairs(GLYPHS) do
      if s:sub(i, i + #g - 1) == g then
        if buf ~= "" then out:insert(pandoc.Str(buf)); buf = "" end
        out:insert(rawi(tex)); i = i + #g; matched = true; break
      end
    end
    if not matched then buf = buf .. s:sub(i, i); i = i + 1 end
  end
  if buf ~= "" then out:insert(pandoc.Str(buf)) end
  return out
end

-- Long identifiers (roles/iam.serviceAccountTokenCreator, principal:// URIs) in inline code never break,
-- and in a table cell they overflow WITHOUT an overfull-box warning. Let them break after . / = and camelCase.
local function Code(c)
  local tex = inline_latex({ c })
  if c.text:find(" ", 1, true) then return rawi(tex) end   -- a whole command: let it break at its spaces
  tex = tex:gsub("([^\\])%.", "%1.\\allowbreak{}")
  tex = tex:gsub("([^\\])/", "%1/\\allowbreak{}")
  tex = tex:gsub("=", "=\\allowbreak{}")
  -- camelCase identifiers (serviceAccountTokenCreator) may break before a capital; skip macro names
  tex = tex:gsub("(%l)(%u)", function(a, b) return a .. "\\allowbreak{}" .. b end)
  tex = tex:gsub("\\(%a*)\\allowbreak{}(%a*)", "\\%1%2")
  return rawi(tex)
end

-- ==highlight==: one box per word, yellow leaders between words, formatting carried onto each word.
local function highlight(inls, wrap)
  local out = pandoc.List()
  for _, el in ipairs(inls) do
    if el.t == "Space" or el.t == "SoftBreak" then
      out:insert(rawi("\\hls{}"))
    elseif el.t == "Strong" then
      out:extend(highlight(el.content, function(s) return wrap("\\textbf{" .. s .. "}") end))
    elseif el.t == "Emph" then
      out:extend(highlight(el.content, function(s) return wrap("\\emph{" .. s .. "}") end))
    elseif el.t == "Span" or el.t == "Link" then
      out:extend(highlight(el.content, wrap))
    else
      out:insert(rawi("\\hlw{" .. wrap(inline_latex({ el })) .. "}"))
    end
  end
  return out
end
local function Span(s)
  if s.classes:includes("mark") then return highlight(s.content, function(x) return x end) end
  return nil
end

------------------------------------------------------------------------ block pass
local function Header(h)
  local text = pandoc.utils.stringify(h.content)
  if h.level == 1 then
    local label, title = text:match("^(%a+ [%w]+)%s*[%-—–]+%s*(.+)$")
    if not label then label, title = "", text end
    local tex = "\\partopener{" .. latex_escape(label) .. "}{" .. latex_escape(title) .. "}"
    if TIGHT[label:upper()] then tex = tex .. "\n\\acetight" end
    return raw(tex)
  end
  if h.level == 2 then
    local first = h.content[1]
    local num = ""
    if first and first.t == "Str" and (first.text:match("^%d+%.%d+$") or first.text:match("^%u%.%d+$")) then
      num = first.text
      h.content:remove(1)
      if h.content[1] and h.content[1].t == "Space" then h.content:remove(1) end
    end
    local plain = latex_escape(pandoc.utils.stringify(h.content))
    local band = "\\sectionband{" .. num .. "}{" .. inline_latex(h.content) .. "}{" .. plain .. "}"
    if plain:lower():find("recall card", 1, true) then band = "\\clearpage\n" .. band end
    return raw(band)
  end
  return nil
end

local function contains_table(blocks)
  local found = false
  pandoc.walk_block(pandoc.Div(blocks), { Table = function() found = true end })
  return found
end

local function panel(env, accent, tint, label, content)
  local out = pandoc.List({ raw(string.format("\\begin{%s}{%s}{%s}{%s}", env, accent, tint, label)) })
  out:extend(content)
  out:insert(raw("\\end{" .. env .. "}"))
  return out
end

local function Div(d)
  if d.classes:includes("objectives") then
    return raw("\\objectivesline{" .. blocks_latex(d.content) .. "}")
  end
  if d.classes:includes("wide") then return d.content end
  if d.classes:includes("cmds") then return d.content end   -- its tables were marked in the first pass
  local env = d.attributes["acepair"] and "acepanelfixed" or "acepanel"
  if d.classes:includes("acethesis") then return panel(env, "thesis", "thesisbg", "", d.content) end
  for kind, spec in pairs(PANELS) do
    if d.classes:includes(kind) then
      if contains_table(d.content) then
        error("ace-theory.lua: a table inside a ::: {." .. kind .. "} panel. Move it out. Panel starts: "
          .. pandoc.utils.stringify(d.content):sub(1, 80))
      end
      local label = d.attributes["title"] or spec[3]
      return panel(env, spec[1], spec[2], latex_escape(label:upper()), d.content)
    end
  end
  return nil
end

local function BlockQuote(q)
  return panel("acepanel", "thesis", "thesisbg", "", q.content)
end

-- Wrap a code line at a space before `width`, preferring a break before a --flag. Continuations are
-- indented four spaces past the line's own indent. Padding before a trailing # comment is collapsed.
local function wrap_line(line, width)
  if #line <= width then return { line } end
  line = line:gsub("%s%s+#", "  #")
  if #line <= width then return { line } end
  local indent = line:match("^(%s*)")
  local cont = indent .. "    "
  local out, rest, first = {}, line, true
  while #rest > width do
    local limit = width
    local cut
    for i = limit, #indent + 8, -1 do
      if rest:sub(i, i + 2) == " --" then cut = i; break end
    end
    if not cut or cut < limit * 0.5 then
      for i = limit, #indent + 8, -1 do
        if rest:sub(i, i) == " " then cut = i; break end
      end
    end
    if not cut then
      for i = limit, #indent + 8, -1 do
        if rest:sub(i, i):match("[,/=&|@%.]") then cut = i + 1; break end
      end
    end
    if not cut then break end
    table.insert(out, (rest:sub(1, cut - 1):gsub("%s+$", "")))
    rest = cont .. rest:sub(cut):gsub("^%s+", "")
    first = false
  end
  table.insert(out, rest)
  return out
end

local function CodeBlock(c)
  if #c.classes == 0 then   -- an ASCII diagram or a log filter: never wrap it
    return { raw("\\begin{codepanel}"), c, raw("\\end{codepanel}") }
  end
  local lines = {}
  for line in (c.text .. "\n"):gmatch("(.-)\n") do
    -- a trailing "# comment" that would force a wrap moves onto its own line above the command
    local cmd, comment = line:match("^(.-%S)%s%s+(#.*)$")
    if cmd and #line > CODE_CHARS and not cmd:find("#", 1, true) then
      table.insert(lines, (line:match("^(%s*)")) .. comment)
      line = cmd
    end
    for _, l in ipairs(wrap_line(line, CODE_CHARS)) do table.insert(lines, l) end
  end
  c.text = table.concat(lines, "\n")
  return { raw("\\begin{codepanel}"), c, raw("\\end{codepanel}") }
end

-- Relative column widths from content: long cells earn width, with diminishing returns.
local function col_weights(t, n, avail)
  local maxl, sum, cnt, word = {}, {}, {}, {}
  for i = 1, n do maxl[i], sum[i], cnt[i], word[i] = 1, 0, 0, 3 end
  -- Measure a cell as the reader sees it: Str text plus inline code, which is raw LaTeX by now. Returns
  -- the total length and the longest unbreakable run (code breaks only at its \allowbreak points, and
  -- counts 1.25x because Menlo is wider than Helvetica).
  local function measure(contents)
    local total, longest, cur = 0, 0, 0
    local function flush() longest = math.max(longest, cur); cur = 0 end
    pandoc.walk_block(pandoc.Div(contents), {
      Str = function(el) cur = cur + #el.text; total = total + #el.text end,
      Space = function() flush(); total = total + 1 end,
      SoftBreak = function() flush(); total = total + 1 end,
      RawInline = function(el)
        local txt = el.text
        if txt:find("\\texttt") then
          local first = true
          for seg in (txt .. "\\allowbreak{}"):gmatch("(.-)\\allowbreak{}") do
            local plain = seg:gsub("\\textbackslash{}", "\\"):gsub("\\%a+", ""):gsub("[{}\\]", "")
            local len = math.ceil(#plain * 1.25)
            if not first then flush() end
            cur = cur + len; total = total + len; first = false
          end
        else
          local plain = txt:gsub("\\%a+", ""):gsub("[{}\\]", "")
          cur = cur + #plain; total = total + #plain
        end
      end,
    })
    flush()
    return total, longest
  end
  local function scan(rows)
    for _, row in ipairs(rows) do
      for i, cell in ipairs(row.cells) do
        if i <= n then
          local l, lw = measure(cell.contents)
          maxl[i] = math.max(maxl[i], l); sum[i] = sum[i] + l; cnt[i] = cnt[i] + 1
          word[i] = math.max(word[i], lw)
        end
      end
    end
  end
  scan(t.head.rows)
  for _, body in ipairs(t.bodies) do scan(body.body) end
  local w, total = {}, 0
  for i = 1, n do
    local avg = cnt[i] > 0 and sum[i] / cnt[i] or 1
    w[i] = math.max(6, math.min(90, 0.6 * avg + 0.4 * math.min(maxl[i], 90)))
    total = total + w[i]
  end
  for i = 1, n do w[i] = w[i] / total end
  -- no column narrower than its longest unbreakable word (avail = characters across the table)
  local need, needsum = {}, 0
  for i = 1, n do need[i] = math.min(0.6, (word[i] + 2) / avail); needsum = needsum + need[i] end
  if needsum >= 1 then
    for i = 1, n do w[i] = need[i] / needsum end
    return w
  end
  local clamped = {}
  for _ = 1, n do
    local fixed, free = 0, 0
    for i = 1, n do
      if clamped[i] or w[i] < need[i] then clamped[i] = true; w[i] = need[i]; fixed = fixed + need[i]
      else free = free + w[i] end
    end
    if free <= 0 then break end
    for i = 1, n do if not clamped[i] then w[i] = w[i] * (1 - fixed) / free end end
  end
  return w
end

local function Table(t)
  local n = #t.colspecs
  local cmds = t.attributes["acecmds"] ~= nil
  t.attributes["acecmds"] = nil
  local w = (cmds and n == 2) and { 0.3, 0.7 } or col_weights(t, n, TABLE_CHARS)
  for i = 1, n do t.colspecs[i] = { t.colspecs[i][1], w[i] } end
  local th = cmds and "\\thcmd " or "\\thcell "
  for _, row in ipairs(t.head.rows) do
    for _, cell in ipairs(row.cells) do
      local b = cell.contents[1]
      if b and (b.t == "Plain" or b.t == "Para") then
        b.content:insert(1, rawi(th))
      else
        cell.contents:insert(1, pandoc.Plain({ rawi(th) }))
      end
    end
  end
  return { raw("{\\rowcolors{2}{band}{white}"), t, raw("}") }
end

------------------------------------------------------------------------ panel pairs
-- Two adjacent short panels print side by side, as in the exam-eve recap. Only top-level neighbours with
-- nothing between them, similar in length, and holding no code or table.
local function panel_kind(b)
  if b.t == "BlockQuote" then return "thesis" end
  if b.t == "Div" then
    for kind in pairs(PANELS) do if b.classes:includes(kind) then return kind end end
  end
  return nil
end

local function pairable(b)
  if not panel_kind(b) then return nil end
  local heavy = false
  pandoc.walk_block(pandoc.Div({ b }), { CodeBlock = function() heavy = true end, Table = function() heavy = true end })
  if heavy then return nil end
  local len = #pandoc.utils.stringify(b)
  return len <= PAIR_MAX and len or nil
end

local function as_pair_member(b)
  if b.t == "BlockQuote" then b = pandoc.Div(b.content, pandoc.Attr("", { "acethesis" })) end
  b.attributes["acepair"] = "1"
  return b
end

local function pair_panels(doc)
  -- (and mark command tables now: the block pass runs bottom-up, so Table sees its Div too late)
  doc.blocks = doc.blocks:walk({ Div = function(d)
    if d.classes:includes("cmds") then
      d.content = d.content:walk({ Table = function(t) t.attributes["acecmds"] = "1"; return t end })
      return d
    end
  end })
  local out, i, blocks = pandoc.List(), 1, doc.blocks
  while i <= #blocks do
    local a, b = blocks[i], blocks[i + 1]
    local la, lb = pairable(a), b and pairable(b)
    if la and lb and math.max(la, lb) / math.max(1, math.min(la, lb)) <= PAIR_RATIO then
      out:insert(raw("\\begin{acepair}"))
      out:insert(as_pair_member(a))
      out:insert(raw("\\acepairsep"))
      out:insert(as_pair_member(b))
      out:insert(raw("\\end{acepair}"))
      i = i + 2
    else
      out:insert(a); i = i + 1
    end
  end
  doc.blocks = out
  return doc
end

return {
  { Pandoc = pair_panels },
  { Str = Str, Code = Code },
  { Span = Span },
  { Header = Header, Div = Div, BlockQuote = BlockQuote, Table = Table, CodeBlock = CodeBlock },
}
