#!/usr/bin/env python3
"""After `course.py merge`: write the YouTube kit for the merged video and for the playlist of parts. Publishes nothing.
Run: python3 publish.py [--youtube-url URL]"""
import json, pathlib, subprocess, sys
OUT = pathlib.Path.home() / "Movies/GCP-ACE-course"; PUB = pathlib.Path(__file__).resolve().parent / "publish"; PUB.mkdir(exist_ok=True)
LIMIT = 5000
url = sys.argv[sys.argv.index("--youtube-url") + 1] if "--youtube-url" in sys.argv else "[add the link after the upload]"
def clock(s):
    s = int(s); h, m, s = s // 3600, s // 60 % 60, s % 60
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"
def probe(p):
    return json.loads(subprocess.run(["ffprobe","-v","error","-show_chapters","-show_format","-of","json",str(p)],check=True,capture_output=True,text=True).stdout)
DISC = ("ABOUT THIS COURSE\nIndependent study material. Not affiliated with, endorsed by, or sponsored by Google. All sample questions are original, written from the public exam guide; none comes from the real exam. "
        "Voices are synthetic (Kokoro-82M, generated locally). Script and diagrams were produced with Claude Code from the author's own theory booklet. Facts marked \"verify\" change often, so check current documentation.")
TOP = ("A full theory course for the Google Cloud Associate Cloud Engineer exam, built against the exam guide live since 30 June 2026: {H} of narrated slides, 100 original exam-style questions with every option explained.\n\n"
       "THE NEW STRUCTURE\nFour sections weighted about 20, 30, 30 and 20. Planning and deploying merged, and operations grew to 30%. New objectives are badged on the slide: Workforce and Workload Identity Federation, Cloud NGFW with secure tags, standalone organizations, GPUs vs TPUs, Hyperdisk, CMEK, Database Center, Personalized Service Health, Cloud Hub, Gemini tooling, Agent Runtime and more.\n\n"
       "HOW TO USE IT\nOne part per sitting. After each exam item there is a silence: pause, name the phrase in the stem that decides it, then hear the explanation. Slides are numbered. Part 10 is for the last 48 hours.")
merged = OUT / "ACE-Full-Course.mp4"; d = probe(merged); dur = float(d["format"]["duration"]); ch = [(float(c["start_time"]), c["tags"]["title"]) for c in d["chapters"]]
hours = f"{dur/3600:.1f} hours"
top = TOP.format(H=hours); bottom = DISC + "\n\n#GoogleCloud #AssociateCloudEngineer #GCP #CloudCertification"
def desc(rows): return top + "\n\nCHAPTERS\n" + "\n".join(f"{clock(s)} {t}" for s, t in rows) + "\n\n" + bottom
rows = ch
if len(desc(rows)) > LIMIT:                       # keep part openers and question sets, thin out sections until it fits
    keep = [r for r in ch if r[1].startswith(("Part ", "Mixed"))]
    rest = [r for r in ch if r not in keep]
    rows = keep
    for r in rest:
        t = sorted(rows + [r])
        if len(desc(t)) <= LIMIT - 40: rows = t
(PUB / "youtube-description-full.txt").write_text(desc(rows) + "\n", encoding="utf-8")
title = "Google Cloud Associate Cloud Engineer: Full Course, June 2026 Exam Guide (100 Practice Questions)"
assert len(title) <= 100, len(title)
parts = sorted(OUT.glob("ACE-Part-*.mp4")); lines = []
for p in parts:
    q = probe(p); n = int(p.stem.split("-")[2]); name = q["chapters"][0]["tags"]["title"]; sect = [(float(c["start_time"]), c["tags"]["title"]) for c in q["chapters"]]
    tt = f"GCP ACE Part {n}/10: " + q["format"]["tags"]["title"].split(": ", 1)[1]
    (PUB / f"youtube-description-part-{n:02d}.txt").write_text(top + "\n\nCHAPTERS\n" + "\n".join(f"{clock(s)} {t}" for s, t in sect) + "\n\n" + bottom + "\n", encoding="utf-8")
    lines.append(f"| {n} | {tt[:100]} | `{p.name}` | {clock(float(q['format']['duration']))} | {len(sect)} | {p.stat().st_size/1e6:.0f} MB |")
(PUB / "youtube.md").write_text(f"""# YouTube kit: GCP ACE course

Generated by `publish.py`. **Nothing is uploaded by the tooling: uploading is your step.**

## Option A: one long video
| Field | Value |
|---|---|
| File | `{merged}` ({merged.stat().st_size/1e9:.2f} GB, {clock(dur)}, {len(ch)} embedded chapters) |
| Title ({len(title)}/100) | {title} |
| Description | `pbcopy < youtube-description-full.txt` ({len(desc(rows))}/5000 characters, {len(rows)} of {len(ch)} chapters listed) |
| Thumbnail | `thumbnail.png` |
| Tags | Google Cloud, Associate Cloud Engineer, GCP ACE, ACE exam, Google Cloud certification, June 2026 exam guide, cloud engineer, GKE, IAM, VPC |

## Option B: a playlist of ten videos
| Part | Title | File | Length | Chapters | Size |
|---|---|---|---|---|---|
{chr(10).join(lines)}

Descriptions: `youtube-description-part-NN.txt`.

## Upload steps, in YouTube Studio
1. Verify the phone at youtube.com/verify, once per channel. Uploads over 15 minutes and custom thumbnails need it. YouTube's limit is 12 hours or 256 GB per video.
2. Upload, paste title and description, add the thumbnail.
3. Audience: not made for kids. Category Education, language English.
4. **Altered content: Yes.** The voices are synthetic; the description says so too.
5. Captions are burned in: **do not upload an SRT**.
6. Keep it **Unlisted** until 1080p has processed, then check the chapters, and a minute at the start and end. Then **Public**.
7. After the upload: `python3 publish.py --youtube-url https://youtu.be/...`
""", encoding="utf-8")
print(f"kit in {PUB}: description {len(desc(rows))}/5000, {len(rows)}/{len(ch)} chapters listed, {clock(dur)}")
