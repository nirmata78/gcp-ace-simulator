#!/usr/bin/env python3
"""Render the question review ledger as a readable Markdown report.

    python scripts/review_report.py [--ledger docs/reviews/2026-11-bank-review.json] [--out docs/reviews/2026-11-bank-review.md]

For every reviewed question the report gives, in this order: the original against the refined question (when it
changed), the audit against the seven criteria of docs/question-standard.md, and the final question with its key and
explanation. Removed questions show only the original text and why they went.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.models import OPTION_KEYS, QuestionBank  # noqa: E402

CRITERIA = {
    "AC1": "Associate scope", "AC2": "Complete scenario", "AC3": "Plausible distractors", "AC4": "One correct answer",
    "AC5": "Explanation", "AC6": "Fair form", "AC7": "Original and current",
}


def _options(opts: dict, key: str | None = None) -> list[str]:
    return [f"- **{k}.** {opts[k]}" + ("  ← key" if k == key else "") for k in OPTION_KEYS]


def render(ledger: dict, bank: QuestionBank) -> str:
    qmap = {q.id: q for q in bank.questions}
    entries = ledger["entries"]
    counts = Counter(e["verdict"] for e in entries)
    out = ["# Question bank review, November 2026", "",
           "Every question was reviewed against [the question standard](../question-standard.md). "
           "This file is generated by `scripts/review_report.py` from "
           "[`2026-11-bank-review.json`](2026-11-bank-review.json); edit the ledger, not this file.", "",
           "| Verdict | Questions |", "|---|---:|"]
    out += [f"| {v} | {counts[v]} |" for v in ("pass", "revised", "removed", "new") if counts[v]]
    out.append("")
    for e in entries:
        q = qmap.get(e["id"])
        out += [f"## {e['id']} · {e['verdict']}", ""]
        orig = e.get("original")
        if e["verdict"] in ("revised", "removed") and orig:
            out += ["**1. Original**", "", orig["question"], ""] + _options(orig["options"], orig["correct_answer"]) + [""]
        out += ["**2. Acceptance criteria audit**", "", "| Criterion | Result |", "|---|---|"]
        out += [f"| {k} {CRITERIA[k]} | {'pass' if v == 'pass' else '**fail**'} |" for k, v in e["ac"].items()]
        out += ["", e["notes"], ""]
        if q is None:
            continue
        out += ["**3. Final question**", "", f"*{q.title}* · {q.objective} {q.subtopic}", "", q.question, ""]
        out += _options(q.options, q.correct_answer) + ["", f"Explanation: {q.explanation.summary}", ""]
        out += [f"- {k}: {q.explanation.option_breakdown[k]}" for k in OPTION_KEYS]
        out += ["", f"Reference: {q.explanation.doc_ref}", ""]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--ledger", type=Path, default=ROOT / "docs/reviews/2026-11-bank-review.json")
    p.add_argument("--out", type=Path, default=ROOT / "docs/reviews/2026-11-bank-review.md")
    args = p.parse_args(argv)
    ledger = json.loads(args.ledger.read_text(encoding="utf-8"))
    args.out.write_text(render(ledger, QuestionBank.load(ROOT / "data")), encoding="utf-8")
    print(f"wrote {args.out.relative_to(ROOT)} ({len(ledger['entries'])} questions)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
